def show_tasks():
    """Display all tasks"""
    conn = sqlite3.connect(KANBAN_DB)
    c = conn.cursor()
    
    c.execute("""
        SELECT b.name, t.id, t.title, t.status, t.priority, t.assignee
        FROM tasks t
        JOIN boards b ON t.board_id = b.id
        ORDER BY b.name, t.status, t.priority
    """)
    
    tasks = c.fetchall()
    conn.close()
    
    if not tasks:
        print("No tasks found")
        return
    
    print("\n📊 KANBAN TASKS")
    print("-"*50)
    
    current_board = None
    for board_name, task_id, title, status, priority, assignee in tasks:
        if board_name != current_board:
            print(f"\n📁 {board_name}")
            current_board = board_name
        
        status_emoji = {
            'todo': '⏳',
            'in-progress': '🔄',
            'done': '✅',
            'blocked': '🚫'
        }.get(status, '❓')
        
        priority_emoji = {
            'high': '🔴',
            'medium': '🟡',
            'low': '🟢'
        }.get(priority, '⚪')
        
        assignee_str = f"@{assignee}" if assignee else "Unassigned"
        print(f"  [{task_id}] {status_emoji} {priority_emoji} {title[:40]:40s} {assignee_str}")
    
    print()

