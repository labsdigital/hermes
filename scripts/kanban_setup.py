#!/usr/bin/env python3
"""
Kanban Setup Script untuk Hermes Agent
Inisialisasi board kanban, config, dan demo tasks
"""

import sqlite3
import os
import json
from datetime import datetime
from pathlib import Path

# Paths
HERMES_HOME = Path.home() / ".hermes"
KANBAN_DB = HERMES_HOME / "kanban.db"
CONFIG_FILE = HERMES_HOME / "config.yaml"
SCRIPT_DIR = Path(__file__).parent

def init_database():
    """Initialize Kanban SQLite database"""
    HERMES_HOME.mkdir(parents=True, exist_ok=True)
    
    conn = sqlite3.connect(KANBAN_DB)
    c = conn.cursor()
    
    # Create boards table
    c.execute('''
        CREATE TABLE IF NOT EXISTS boards (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT UNIQUE NOT NULL,
            description TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            status TEXT DEFAULT 'active'
        )
    ''')
    
    # Create tasks table
    c.execute('''
        CREATE TABLE IF NOT EXISTS tasks (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            board_id INTEGER NOT NULL,
            title TEXT NOT NULL,
            description TEXT,
            status TEXT DEFAULT 'todo',
            priority TEXT DEFAULT 'medium',
            assignee TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            completed_at TIMESTAMP,
            blocked_reason TEXT,
            parent_task_id INTEGER,
            FOREIGN KEY (board_id) REFERENCES boards(id),
            FOREIGN KEY (parent_task_id) REFERENCES tasks(id)
        )
    ''')
    
    # Create comments table
    c.execute('''
        CREATE TABLE IF NOT EXISTS comments (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            task_id INTEGER NOT NULL,
            author TEXT,
            content TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (task_id) REFERENCES tasks(id)
        )
    ''')
    
    # Create indexes
    c.execute('CREATE INDEX IF NOT EXISTS idx_tasks_board ON tasks(board_id)')
    c.execute('CREATE INDEX IF NOT EXISTS idx_tasks_status ON tasks(status)')
    c.execute('CREATE INDEX IF NOT EXISTS idx_tasks_assignee ON tasks(assignee)')
    
    conn.commit()
    conn.close()
    print(f"✓ Database initialized: {KANBAN_DB}")

def add_demo_board():
    """Add a demo board for testing"""
    conn = sqlite3.connect(KANBAN_DB)
    c = conn.cursor()
    
    # Check if demo board exists
    c.execute("SELECT id FROM boards WHERE name = ?", ("Demo-Proyek",))
    if c.fetchone():
        print("✓ Demo board already exists")
        conn.close()
        return
    
    # Insert demo board
    c.execute(
        "INSERT INTO boards (name, description) VALUES (?, ?)",
        ("Demo-Proyek", "Board demo untuk testing Kanban")
    )
    board_id = c.lastrowid
    
    # Insert demo tasks
    demo_tasks = [
        ("Tulis Bab 1", "Mulai menulis chapter pertama", "todo", "high", "atlas", None),
        ("Review Bab 1", "Review dan revisi chapter 1", "todo", "medium", None, None),
        ("Generate Ilustrasi", "Buat ilustrasi SVG dan PNG", "in-progress", "high", "zetta", None),
        ("Upload ke GitHub", "Commit dan push changes", "todo", "medium", "max", None),
        ("Deploy ke FTP", "Upload files ke server", "blocked", "low", None, "Menunggu review"),
    ]
    
    for task in demo_tasks:
        title, desc, status, priority, assignee, blocked_reason = task
        
        c.execute(
            """INSERT INTO tasks 
               (board_id, title, description, status, priority, assignee, blocked_reason)
               VALUES (?, ?, ?, ?, ?, ?, ?)""",
            (board_id, title, desc, status, priority, assignee, blocked_reason)
        )
    
    conn.commit()
    conn.close()
    print("✓ Demo board dan tasks created")

def update_config():
    """Update Hermes config.yaml with kanban settings"""
    if not CONFIG_FILE.exists():
        # Create new config
        config_content = """# Hermes Agent Configuration
# Generated by kanban-setup.py

display:
  interface: tui
  skin: default

delegation:
  model: stealth/ox-alpha
  provider: openrouter
  max_concurrent_children: 3

kanban:
  enabled: true
  dispatch_in_gateway: true
  failure_limit: 2
"""
        CONFIG_FILE.write_text(config_content)
        print(f"✓ Config created: {CONFIG_FILE}")
    else:
        # Append kanban config if not exists
        content = CONFIG_FILE.read_text()
        if "kanban:" not in content:
            with open(CONFIG_FILE, 'a') as f:
                f.write("""
# Kanban Configuration
kanban:
  enabled: true
  dispatch_in_gateway: true
  failure_limit: 2
""")
            print(f"✓ Kanban config added to: {CONFIG_FILE}")
        else:
            print("✓ Kanban config already exists")

